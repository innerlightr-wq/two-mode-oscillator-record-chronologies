#!/usr/bin/env python3
"""tables.py -- emit the machine-generated classification and exclusion tables.

Writes, for each slope: every normalised orbit representative with its signed norm, its
four-way classification, and -- for each excluded orbit -- a CHECKABLE exclusion witness: the
competitor orbit, the period offset d, the sign of Gamma_d that decides it, and the period from
which that sign is certified to dominate.  A reader can re-derive any single row from the
formulas in PROOF_OR_OBSTRUCTION.md sections 4-6 without re-running a search.

Outputs:  tables/classification.csv, tables/exclusions.csv, tables/classification.tex,
          tables/exclusions_summary.tex
"""
import os, csv
from quad import Q
from setups import PHI, S3, SQ3
from orbits import admissible_primitive_orbits, ring_elt, state_from_ab, mul, rho
from certificate import (cutoff, classify, gamma_d, least_decided_period, order_UV,
                         least_ordered_period, tie_sign, delta_rho)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables")
os.makedirs(OUT, exist_ok=True)

def fnum(q, D):
    return float(q.a) + float(q.b)*float(D)**0.5

def first_positive_state(S, a, b, tries=40):
    for _ in range(tries):
        m, k = state_from_ab(S, a, b)
        if m > 0 and k > 0: return (m, k)
        a, b = mul(S, (a, b), rho(S))
    return None

def witness(S, orbs, Bo):
    """The competitor that excludes orbit Bo, with the deciding data."""
    parities = (0,1) if delta_rho(S) == -1 else (0,)
    for A in orbs:
        for par in parities:
            if A is Bo: dl_ = [1]
            else:
                U0, _ = order_UV(S, A, Bo, 0, parity=par)
                dl_ = [0] if U0.sign() > 0 else [1]
            for d in dl_:
                G = gamma_d(S, A, Bo, d)
                if G.sign() < 0:
                    P = least_decided_period(S, A, Bo, d, G)
                    return dict(N_A=A[1], d=d, parity=par, sign_gamma=G.sign(),
                                gamma=str(G), certified_from_period=P,
                                rule="sign(Gamma_d) < 0: B strictly loses to A")
                if G.sign() == 0:
                    ts = tie_sign(S, A, Bo, d, d+par)
                    if ts > 0:
                        return dict(N_A=A[1], d=d, parity=par, sign_gamma=0, gamma="0",
                                    certified_from_period=None,
                                    rule="Gamma_d = 0 and the integer tie rule gives A ahead")
    return None

rows_c, rows_e = [], []
for S in (PHI, S3, SQ3):
    B = cutoff(S); orbs = admissible_primitive_orbits(S, B); _, cls = classify(S, B)
    for r in cls:
        absN, N, a, b, status = r
        eta = ring_elt(S, a, b)
        st = first_positive_state(S, a, b)
        rows_c.append(dict(slope=S.name, cutoff=B, abs_N=absN, N_rep=N,
                           eta_a=str(eta.a), eta_b=str(eta.b), eta_num="%.10f" % fnum(eta, S.D),
                           first_positive_state=("(%d,%d)" % st) if st else "",
                           classification=status))
        if status == "excluded":
            w = witness(S, orbs, r[:4])
            rows_e.append(dict(slope=S.name, abs_N=absN, N_rep=N,
                               eta_num="%.10f" % fnum(eta, S.D),
                               competitor_N_A=w["N_A"], offset_d=w["d"], parity=w["parity"],
                               sign_gamma=w["sign_gamma"], gamma=w["gamma"],
                               certified_from_period=w["certified_from_period"],
                               rule=w["rule"]))

with open(os.path.join(OUT, "classification.csv"), "w", newline="") as f:
    wr = csv.DictWriter(f, fieldnames=list(rows_c[0].keys())); wr.writeheader(); wr.writerows(rows_c)
with open(os.path.join(OUT, "exclusions.csv"), "w", newline="") as f:
    wr = csv.DictWriter(f, fieldnames=list(rows_e[0].keys())); wr.writeheader(); wr.writerows(rows_e)

NAME = {"phi": r"$\varphi$", "1+sqrt3": r"$1+\sqrt3$", "sqrt3": r"$\sqrt3$"}
with open(os.path.join(OUT, "classification.tex"), "w") as f:
    f.write("% machine-generated by tables.py -- do not edit\n")
    f.write("\\begin{longtable}{llrrlll}\n\\hline\n")
    hdr = ("$\\alpha$ & cutoff & $|N|$ & $N_{\\mathrm{rep}}$ & $\\eta$ (rep) & "
           "first positive state & class \\\\\n\\hline\n")
    f.write(hdr + "\\endfirsthead\n\\hline\n" + hdr + "\\endhead\n"
            "\\hline\n\\multicolumn{7}{r}{\\footnotesize continued}\\\\\n\\endfoot\n"
            "\\hline\n\\endlastfoot\n")
    for r in rows_c:
        f.write("%s & %d & %d & %+d & %.6f & %s & %s \\\\\n" %
                (NAME[r["slope"]], r["cutoff"], r["abs_N"], r["N_rep"], float(r["eta_num"]),
                 r["first_positive_state"] or "--", r["classification"]))
    f.write("\\end{longtable}\n")
with open(os.path.join(OUT, "exclusions_summary.tex"), "w") as f:
    f.write("% machine-generated by tables.py -- do not edit\n")
    f.write("\\begin{longtable}{lrrrrrl}\n\\hline\n")
    hdr = ("$\\alpha$ & $|N|$ & $N_{\\mathrm{rep}}$ & $N_A$ & $d$ & from $p$ & "
           "deciding rule \\\\\n\\hline\n")
    f.write(hdr + "\\endfirsthead\n\\hline\n" + hdr + "\\endhead\n"
            "\\hline\n\\multicolumn{7}{r}{\\footnotesize continued}\\\\\n\\endfoot\n"
            "\\hline\n\\endlastfoot\n")
    for r in rows_e:
        f.write("%s & %d & %+d & %+d & %d & %s & %s \\\\\n" %
                (NAME[r["slope"]], r["abs_N"], r["N_rep"], r["competitor_N_A"], r["offset_d"],
                 r["certified_from_period"] if r["certified_from_period"] is not None else "--",
                 "$\\operatorname{sign}\\Gamma_d<0$" if r["sign_gamma"] < 0 else "tie rule"))
    f.write("\\end{longtable}\n")

print("classification rows: %d   exclusion rows: %d" % (len(rows_c), len(rows_e)))
for S in (PHI, S3, SQ3):
    sub = [r for r in rows_c if r["slope"] == S.name]
    from collections import Counter
    print("  %-9s %d orbits: %s" % (S.name, len(sub), dict(Counter(r["classification"] for r in sub))))
print("-> tables/classification.csv, tables/exclusions.csv, tables/classification.tex, tables/exclusions_summary.tex")
